// Wiring for the artifact-cluster engagement actions on /p/[slug] pages.
// Loaded from a separate file so /p/[slug] HTML stays small and the
// browser can cache this once per origin.
//
// Reads the slug from data-slug on the cluster root. Wires:
//   - Upvote: POST /api/vote, optimistic count update, "voted" lock
//   - Share:  small period-style modal (Copy / Email / native Share / Close)
//   - Report: mailto:webmaster@ainetscape.com with the URL pre-filled

(function () {
  const cluster = document.querySelector('[data-artifact-cluster]');
  if (!cluster) return;
  const slug = cluster.getAttribute('data-slug') || '';
  if (!slug) return;
  const shareUrl = location.origin + '/p/' + slug;

  // ---------------- Upvote ----------------
  const upvoteBtn = cluster.querySelector('[data-action="upvote"]');
  const voteCount = cluster.querySelector('[data-vote-count]');
  if (upvoteBtn) {
    upvoteBtn.addEventListener('click', async function (ev) {
      ev.preventDefault();
      if (upvoteBtn.classList.contains('voted') || upvoteBtn.disabled) return;
      upvoteBtn.disabled = true;
      try {
        const resp = await fetch('/api/vote', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ slug: slug })
        });
        const j = await resp.json().catch(function () { return {}; });
        if (resp.ok && typeof j.upvotes === 'number' && voteCount) {
          voteCount.textContent = formatCount(j.upvotes);
        }
        upvoteBtn.classList.add('voted');
      } catch (_) {
        upvoteBtn.disabled = false;
      }
    });
  }

  // ---------------- Share ----------------
  const shareBtn = cluster.querySelector('[data-action="share"]');
  if (shareBtn) {
    shareBtn.addEventListener('click', function (ev) {
      ev.preventDefault();
      openShareDialog();
    });
  }

  // ---------------- Report ----------------
  const reportBtn = cluster.querySelector('[data-action="report"]');
  if (reportBtn) {
    reportBtn.addEventListener('click', function (ev) {
      ev.preventDefault();
      const subject = 'Report — ' + shareUrl;
      const body = 'Reporting page: ' + shareUrl + '\n\n' +
                   'Reason (please describe):\n\n';
      window.location.href = 'mailto:webmaster@ainetscape.com' +
        '?subject=' + encodeURIComponent(subject) +
        '&body=' + encodeURIComponent(body);
    });
  }

  // ============================================================
  // Share dialog — period-styled modal mirroring the homepage editor.
  // Copy / Email / Share... / Close. Email body mirrors the homepage's
  // composeSharePayload format so both surfaces share the same voice.
  // ============================================================
  function composePayload() {
    const title = (document.title || '').trim() || 'Untitled';
    const subject = title + " (Generated by AI Netscape - 1997's AI-Powered HTML Editor)";
    const body =
      'Check out the page I just generated on AI Netscape:\n\n' +
      '  ' + title + '\n' +
      '  ' + shareUrl + '\n\n' +
      '— — —\n\n' +
      'AI Netscape is a 1997-era HTML editor with one impossible button: ' +
      'a modern AI that builds a complete state-of-the-art website from a ' +
      'one-line brief, in under a minute. No signup, no payment, modem ' +
      'sounds included.\n\n' +
      'Try it yourself: https://ainetscape.com\n\n' +
      '— — —\n\n' +
      "AI Netscape 4.7  •  1997's AI-Powered HTML Editor  •  © 1997 AI Netscape, All Rights Reserved";
    return { title: title, subject: subject, body: body };
  }

  let dialogEl = null;
  function openShareDialog() {
    if (dialogEl) return;
    const hasNativeShare = typeof navigator !== 'undefined' && typeof navigator.share === 'function';

    const wrap = document.createElement('div');
    wrap.setAttribute('role', 'dialog');
    wrap.setAttribute('aria-modal', 'true');
    wrap.style.cssText =
      'position:fixed; inset:0; z-index:2147483647; ' +
      'background:rgba(0,0,0,0.45); display:flex; align-items:center; ' +
      'justify-content:center; padding:12px;';

    wrap.innerHTML =
      '<div style="background:#c0c0c0; border:2px solid; ' +
        'border-color:#fff #404040 #404040 #fff; box-shadow:2px 2px 0 rgba(0,0,0,0.4); ' +
        'max-width:460px; width:100%; font-family:\'MS Sans Serif\',Tahoma,sans-serif;">' +

        '<div style="background:#000080; color:#fff; padding:3px 6px; ' +
          'font-weight:bold; font-size:11px; display:flex; align-items:center;">' +
          '<span style="flex:1;">Share This Page</span>' +
          '<button data-share-close type="button" aria-label="Close" ' +
            'style="background:#c0c0c0; border:1px solid; ' +
            'border-color:#fff #404040 #404040 #fff; color:#000; ' +
            'font:bold 9px sans-serif; width:16px; height:14px; ' +
            'line-height:10px; padding:0; cursor:pointer;">✕</button>' +
        '</div>' +

        '<div style="padding:12px;">' +
          '<div style="font-size:11px; margin-bottom:10px;">' +
            'Your page has its own URL. Anyone with this link can view it.' +
          '</div>' +
          '<input data-share-url type="text" readonly value="' + escapeAttr(shareUrl) + '" ' +
            'style="width:100%; box-sizing:border-box; padding:4px 6px; ' +
            'font:11px \'Courier New\',monospace; border:1px solid #404040; background:#fff;" />' +
          '<div data-share-toast style="font-size:10px; color:#080; ' +
            'margin-top:6px; min-height:14px; visibility:hidden;">' +
            'Link copied to clipboard.</div>' +
          '<div style="display:flex; gap:6px; justify-content:flex-end; margin-top:6px; flex-wrap:wrap;">' +
            btn('share-copy', 'Copy Link', true) +
            btn('share-email', 'Email', false) +
            (hasNativeShare ? btn('share-native', 'Share…', false) : '') +
            btn('share-close-2', 'Close', false) +
          '</div>' +
        '</div>' +
      '</div>';

    document.body.appendChild(wrap);
    dialogEl = wrap;

    wrap.addEventListener('click', function (e) {
      if (e.target === wrap) closeShareDialog();
    });
    on(wrap, '[data-share-close]', closeShareDialog);
    on(wrap, '[data-action-dlg="share-close-2"]', closeShareDialog);
    on(wrap, '[data-action-dlg="share-copy"]', copyToClipboard);
    on(wrap, '[data-action-dlg="share-email"]', emailShare);
    if (hasNativeShare) on(wrap, '[data-action-dlg="share-native"]', nativeShare);

    const escListener = function (e) {
      if (e.key === 'Escape') closeShareDialog();
    };
    document.addEventListener('keydown', escListener);
    wrap._escListener = escListener;

    setTimeout(function () {
      const inp = wrap.querySelector('[data-share-url]');
      if (inp) { inp.focus(); inp.select(); }
    }, 0);
  }
  function closeShareDialog() {
    if (!dialogEl) return;
    if (dialogEl._escListener) document.removeEventListener('keydown', dialogEl._escListener);
    dialogEl.remove();
    dialogEl = null;
  }
  function copyToClipboard() {
    const toast = dialogEl && dialogEl.querySelector('[data-share-toast]');
    const finish = function (ok) {
      if (toast) {
        toast.textContent = ok ? 'Link copied to clipboard.'
          : 'Could not copy — select the URL above and copy manually.';
        toast.style.color = ok ? '#080' : '#a00';
        toast.style.visibility = 'visible';
      }
    };
    try {
      navigator.clipboard.writeText(shareUrl).then(
        function () { finish(true); },
        function () { finish(false); }
      );
    } catch (_) { finish(false); }
  }
  function emailShare() {
    const p = composePayload();
    window.location.href = 'mailto:?subject=' + encodeURIComponent(p.subject) +
      '&body=' + encodeURIComponent(p.body);
  }
  function nativeShare() {
    const p = composePayload();
    try {
      navigator.share({ title: p.subject, text: p.body, url: shareUrl })
        .then(function () { closeShareDialog(); }, function () {});
    } catch (_) {}
  }

  // ---------------- Helpers ----------------
  function btn(key, label, primary) {
    const style =
      'font:11px \'MS Sans Serif\',Tahoma,sans-serif; color:#000; ' +
      'background:#c0c0c0; border:2px solid; ' +
      'border-color:#fff #404040 #404040 #fff; ' +
      'padding:3px 14px; min-width:74px; cursor:pointer;' +
      (primary ? ' font-weight:bold;' : '');
    return '<button type="button" data-action-dlg="' + key + '" ' +
      'style="' + style + '">' + label + '</button>';
  }
  function on(root, sel, fn) {
    root.querySelectorAll(sel).forEach(function (el) {
      el.addEventListener('click', fn);
    });
  }
  function formatCount(n) {
    n = Number(n) || 0;
    return n < 1000 ? String(n) : n.toLocaleString('en-US');
  }
  function escapeAttr(s) {
    return String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;')
      .replace(/</g, '&lt;').replace(/>/g, '&gt;');
  }
})();
